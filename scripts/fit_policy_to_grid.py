"""Idea 4: warm-start the weight policy from the situation grid, then adapt.

    python3 scripts/fit_policy_to_grid.py --grid situation_demands_qc.json
    python3 scripts/fit_policy_to_grid.py ... --eval        # + frozen laps, needs acados

The learner's problem so far has been its signal: TD on the controller's own
cost points a fixed direction (TODO 2w), and the fitted critic's direction
comes from white theta-noise that the horizon mostly averages away (2s). But
there is a learning signal already on disk that is neither: the situation
grid (2y) drove every (q_v, k_v, q_c) vector in every (sector, entry-speed)
cell and kept the winner. That is a measured target for what the weights
should be in each situation.

So: fit the policy network to the grid FIRST -- supervised, no noise, no
critic -- and let online learning start from a network that is already a
function of the situation. The fit uses the same machinery the tuner uses
(``WeightPolicy.step`` forward, ``WeightPolicy.grads`` backward), on
sequences of features generated by walking the track at each grid speed, so
the recurrent cell sees inputs in the order it will see them when driving.

The output box is DATA-DRIVEN: the grid's winners span q_v 0.2-2.0 and
q_c 0.1-1.0, far outside the factor-2 adaptation box. The box is drawn to
contain every target with a factor-1.5 margin, intersected with the global
limits. Online adaptation then happens inside a box that the grid says is
worth exploring, rather than one drawn around a single anchor.
"""

