#!/usr/bin/env python3
"""Fig 3 (RQ1, qualification online-learning on the ICRA track icra_t2_smooth).
Three ICRA-house-style panels from results/race/qualify_icra_learn.npz (generated by
results/race/qualify_icra_learn.py, which runs the real deploy controller on the v060 acados):
  (a) the driven line on the real map, coloured by SPEED -- the racing line the tuner settles into;
  (b) the same line coloured by WEIGHT-ADAPTATION intensity ||d(log theta)/dt|| -- WHERE it refines
      (hot = the corners where the base policy left margin);
  (c) the keep-best LAP RATCHET -- every lap's time, the banked-best staircase monotone down, slower
      or off-track attempts reverted (hollow) -- the safe-refinement story in RQ1.
DATA-ONLY (no acados): reads the npz + the committed boundaries file. Reproduce:
    python3 tools/paper_qualify_icra_fig.py
"""
import sys
from pathlib import Path
import numpy as np
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.cm as cm
from matplotlib.collections import LineCollection

ROOT = Path("/home/poxx/github/mpcc-online-tuning"); sys.path.insert(0, str(ROOT))
NPZ = ROOT / "results/race/qualify_icra_learn.npz"
BND = ROOT / "mpcc_tuning/tracks/icra_t2_smooth_boundaries.npz"
FIG = Path("/home/poxx/github/R-AL-MPCC_online_learning/figures/qualify_icra_learn.pdf")
# Times-compatible serif (Nimbus Roman) + STIX math so the rendered PDF matches the paper's
# Times type and the pgfplots (TikZ) figures -- not matplotlib's default DejaVu Serif.
plt.rcParams.update({"font.family": "serif",
                     "font.serif": ["Nimbus Roman", "Liberation Serif", "DejaVu Serif"],
                     "mathtext.fontset": "stix", "font.size": 9})


def draw_track_bg(ax, b, scalebar=True):
    """Clean paper style: white ground (no grey fill, no frame), thin grey track boundaries,
    dashed raceline, and a 1 m scale bar tucked into the bottom-left margin (clear of the track)."""
    ax.plot(b["left_x"], b["left_y"], color="0.6", lw=0.8, zorder=1)
    ax.plot(b["right_x"], b["right_y"], color="0.6", lw=0.8, zorder=1)
    if "ref_x" in b.files:
        ax.plot(b["ref_x"], b["ref_y"], color="0.45", lw=0.8, ls=(0, (4, 3)), zorder=1.5)
    xs = np.r_[b["left_x"], b["right_x"]]; ys = np.r_[b["left_y"], b["right_y"]]
    xlo, xhi, ylo, yhi = xs.min(), xs.max(), ys.min(), ys.max()
    ax.set_xlim(xlo - 0.3, xhi + 0.3); ax.set_ylim(ylo - 0.55, yhi + 0.25)
    if scalebar:                                   # in the dedicated bottom margin, below the track
        y = ylo - 0.34
        ax.plot([xlo, xlo + 1.0], [y, y], color="k", lw=1.8, zorder=6)
        ax.text(xlo + 0.5, y - 0.04, "1 m", ha="center", va="top", fontsize=7, zorder=6)
    ax.set_aspect("equal"); ax.set_xticks([]); ax.set_yticks([])
    for s in ax.spines.values():
        s.set_visible(False)
    ax.grid(False)


def _panel_label(ax, s, inside=True):
    """Paper subfigure label '(a)' at the panel's top-left, in place of a title."""
    if inside:
        ax.text(0.015, 0.99, s, transform=ax.transAxes, fontsize=10, fontweight="bold",
                va="top", ha="left")
    else:
        ax.text(-0.02, 1.02, s, transform=ax.transAxes, fontsize=10, fontweight="bold",
                va="bottom", ha="left")


def adapt_intensity(TH, win=25):
    """||d(log theta)/dt|| as a situation-driven adaptation signal (copied from
    paper_race_weight_learning_map.adapt_intensity): smooth each weight (kills the zero-mean explore
    jitter), z-score per weight, L2 deviation of the smoothed vector from its mean. Hot = refines most."""
    logw = np.log(np.clip(np.asarray(TH, float), 1e-6, None))
    k = np.ones(int(win)) / int(win)
    sm = np.apply_along_axis(lambda c: np.convolve(c, k, mode="same"), 0, logw)
    z = (sm - sm.mean(0)) / (sm.std(0) + 1e-6)
    return np.linalg.norm(z, axis=1)


def _color_line(ax, X, Y, Cval, cmap, vmax, lw=2.2):
    pts = np.array([X, Y]).T.reshape(-1, 1, 2); segs = np.concatenate([pts[:-1], pts[1:]], axis=1)
    lc = LineCollection(segs, cmap=cmap, norm=plt.Normalize(0, vmax), linewidths=lw, zorder=4)
    lc.set_array(np.asarray(Cval)[:-1]); return ax.add_collection(lc)


def main():
    if not NPZ.exists():
        print(f"(missing {NPZ} -- run `python3 results/race/qualify_icra_learn.py 3600` first)"); return
    d = np.load(NPZ, allow_pickle=True); b = np.load(BND)
    xy = np.asarray(d["xy"], float); EX, EY = xy[:, 0], xy[:, 1]
    vh = np.asarray(d["vh"], float); TH = np.asarray(d["th_hist"], float)
    off = np.asarray(d["off"], bool); rew = np.asarray(d["reward"], float)
    dt = float(d["dt"]); t = np.arange(len(vh)) * dt
    inten = adapt_intensity(TH); vmax_a = float(np.percentile(inten, 98)) or 1.0
    lt = np.asarray(d["lap_times"], float)
    banked = [str(x) for x in np.asarray(d["lap_banked"], dtype=object).tolist()]

    fig = plt.figure(figsize=(7.0, 4.3))
    gs = fig.add_gridspec(2, 2, height_ratios=[1.3, 0.72], hspace=0.16, wspace=0.06)
    axA = fig.add_subplot(gs[0, 0]); axB = fig.add_subplot(gs[0, 1]); axC = fig.add_subplot(gs[1, :])

    # (a) speed map
    draw_track_bg(axA, b, scalebar=True)
    scA = _color_line(axA, EX, EY, vh, "viridis", float(np.percentile(vh, 99)))
    axA.plot(EX[0], EY[0], marker="o", mfc="none", mec="k", mew=1.4, ms=8, zorder=6)
    cbA = fig.colorbar(scA, ax=axA, shrink=0.8, pad=0.02); cbA.set_label("speed [m/s]", fontsize=8)
    cbA.ax.tick_params(labelsize=7); _panel_label(axA, "(a)")

    # (b) adaptation-intensity map
    draw_track_bg(axB, b, scalebar=False)
    scB = _color_line(axB, EX, EY, inten, "inferno", vmax_a)
    axB.plot(EX[0], EY[0], marker="o", mfc="none", mec="k", mew=1.4, ms=8, zorder=6)
    if off.any():
        axB.scatter(EX[off], EY[off], s=10, marker="x", color="red", lw=0.8, zorder=5, label="off-track (reverted)")
        axB.legend(fontsize=6.5, loc="lower right", framealpha=0.9)
    cbB = fig.colorbar(scB, ax=axB, shrink=0.8, pad=0.02)
    cbB.set_label(r"$\|\mathrm{d}\log\theta/\mathrm{d}t\|$", fontsize=8); cbB.ax.tick_params(labelsize=7)
    _panel_label(axB, "(b)")

    # (c) keep-best lap ratchet
    if lt.size:
        li = np.arange(1, lt.size + 1)
        best = np.minimum.accumulate(lt)                      # banked-best so-far (monotone down)
        is_rev = np.array([("revert" in banked[i] if i < len(banked) else False) for i in range(lt.size)])
        axC.step(li, best, where="post", color="#1f4e8c", lw=1.6, zorder=2, label="banked best (keep-best)")
        axC.scatter(li[~is_rev], lt[~is_rev], s=28, color="#1f4e8c", zorder=3, label="lap banked")
        axC.scatter(li[is_rev], lt[is_rev], s=28, facecolor="none", edgecolor="#c23b3b", lw=1.1,
                    zorder=3, label="slower/off → reverted")
        axC.set_xlabel("lap", fontsize=9); axC.set_ylabel("lap time [s]", fontsize=9)
        axC.set_xticks(li); axC.grid(alpha=0.3)
        axC.legend(fontsize=7, loc="upper right", framealpha=0.9, ncol=1)
    else:
        axC.text(0.5, 0.5, "no completed laps logged", ha="center", va="center", transform=axC.transAxes)
    _panel_label(axC, "(c)", inside=False)

    FIG.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG, bbox_inches="tight"); fig.savefig(FIG.with_suffix(".png"), dpi=200, bbox_inches="tight")
    print("wrote", FIG)
    print(f"  laps={float(d['laps']):.2f}  banks={int(d['banks'])}/{len(banked)}  off_ticks={int(off.sum())}/{len(off)}")
    print(f"  lap_times[s]={[round(x,1) for x in lt.tolist()]}")
    print(f"  speed mean={vh.mean():.2f} max={vh.max():.2f}  solve p50={np.percentile(d['solve'],50):.0f}ms")


if __name__ == "__main__":
    main()
