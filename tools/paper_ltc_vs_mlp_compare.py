"""LTC vs MLP: do the two tuners emit different MPCC WEIGHTS and drive different CAR STATES, even when the
outcome is the same? Overlays the emitted weights (k_v, q_v, r_a, q_c) and the speed over the run, plus the
two trajectories, from the saved online _ra10conf runs. Reproducible (no acados).

    python3 tools/paper_ltc_vs_mlp_compare.py --case overtake_blind --seed 0 --tag _ra10conf
"""
import sys, argparse
from pathlib import Path
import numpy as np
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.collections import LineCollection

ROOT = Path("/home/poxx/github/mpcc-online-tuning"); sys.path.insert(0, str(ROOT))
OUT = ROOT / "results/race_phase2"; TZ = OUT / "tikz"
from mpcc_tuning.mpcc import WEIGHT_NAMES   # (q_c,q_l,q_v,r_d,r_a,r_dv,d_obs,k_v,d_bound)
IDX = {n: i for i, n in enumerate(WEIGHT_NAMES)}
LTCC, MLPC = "#1f4e8c", "#e8820e"
DT = 0.05


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--case", default="overtake_blind")
    ap.add_argument("--seed", type=int, default=0); ap.add_argument("--tag", default="_ra10conf")
    a = ap.parse_args()
    b = np.load(ROOT / "mpcc_tuning/tracks/icra_t2_smooth_boundaries.npz")
    d = {arm: np.load(OUT / f"sensor_{a.case}_{arm}_{a.seed}{a.tag}.npz") for arm in ("ltc", "mlp")}

    print(f"=== {a.case} seed {a.seed}: LTC vs MLP mean emitted weight + state ===")
    print(f"{'signal':>10} {'LTC':>8} {'MLP':>8} {'rel.diff':>9}")
    for n in ("k_v", "q_v", "r_a", "q_c"):
        lv = float(np.mean(d["ltc"]["THETA"][:, IDX[n]])); mv = float(np.mean(d["mlp"]["THETA"][:, IDX[n]]))
        print(f"{n:>10} {lv:>8.3f} {mv:>8.3f} {(lv-mv)/max(abs(mv),1e-6):>8.0%}")
    for n in ("V",):
        lv = float(np.mean(d["ltc"][n])); mv = float(np.mean(d["mlp"][n]))
        print(f"{n+' (mean)':>10} {lv:>8.3f} {mv:>8.3f} {(lv-mv)/max(abs(mv),1e-6):>8.0%}")

    sigs = [("k_v", "k_v (speed fraction)"), ("q_v", "q_v (aggression)"),
            ("r_a", "r_a (accel penalty)"), ("q_c", "q_c (line-keeping)")]
    fig, axs = plt.subplots(2, 3, figsize=(15, 7.5))
    for ax, (n, lbl) in zip(axs.ravel()[:4], sigs):
        for arm, c in (("ltc", LTCC), ("mlp", MLPC)):
            z = d[arm]; t = np.arange(len(z["THETA"])) * DT
            ax.plot(t, z["THETA"][:, IDX[n]], color=c, lw=1.2, label=arm.upper())
        ax.set_xlabel("time (s)"); ax.set_ylabel(lbl); ax.grid(alpha=.3); ax.legend(fontsize=8)
    axV = axs[1][1]
    for arm, c in (("ltc", LTCC), ("mlp", MLPC)):
        z = d[arm]; t = np.arange(len(z["V"])) * DT; axV.plot(t, z["V"], color=c, lw=1.2, label=arm.upper())
    axV.axhline(2.5, color="0.5", ls="--", lw=.8, label="~corridor ceiling"); axV.set_xlabel("time (s)")
    axV.set_ylabel("speed V (m/s)"); axV.grid(alpha=.3); axV.legend(fontsize=8)
    axT = axs[1][2]
    axT.plot(b["left_x"], b["left_y"], color="0.6", lw=.8); axT.plot(b["right_x"], b["right_y"], color="0.6", lw=.8)
    for arm, c in (("ltc", LTCC), ("mlp", MLPC)):
        z = d[arm]; axT.plot(z["EX"], z["EY"], color=c, lw=1.4, alpha=.8, label=arm.upper())
    axT.set_aspect("equal"); axT.set_xticks([]); axT.set_yticks([]); axT.legend(fontsize=8); axT.set_title("trajectories", fontsize=9)
    fig.suptitle(f"LTC vs MLP under the real sensor ({a.case.replace('_',' ')}, seed {a.seed}): "
                 "same clean outcome, different weights/line", fontsize=11)
    for e in ("pdf", "png"):
        fig.savefig(OUT / f"fig_ltc_vs_mlp_{a.case}_{a.seed}.{e}", dpi=150, bbox_inches="tight")
    plt.close(fig); print(f"wrote {OUT}/fig_ltc_vs_mlp_{a.case}_{a.seed}.pdf (+.png)")

    TZ.mkdir(parents=True, exist_ok=True)
    for arm in ("ltc", "mlp"):
        z = d[arm]; t = np.arange(len(z["V"])) * DT; ds = max(1, len(t) // 1500)
        with open(TZ / f"ltcmlp_{a.case}_{arm}.dat", "w") as fh:
            fh.write("t kv qv V\n")
            [fh.write(f"{t[i]:.3f} {z['THETA'][i,IDX['k_v']]:.4f} {z['THETA'][i,IDX['q_v']]:.4f} {z['V'][i]:.4f}\n")
             for i in range(0, len(t), ds)]
    (TZ / f"fig_ltc_vs_mlp_{a.case}_{a.seed}.tex").write_text(
        "% Auto-generated by tools/paper_ltc_vs_mlp_compare.py  (k_v over time, LTC vs MLP)\n"
        "\\begin{tikzpicture}\n\\begin{axis}[xlabel={time (s)}, ylabel={$k_v$ (speed fraction)}, width=9cm, height=5.5cm, grid=both, legend pos=north east]\n"
        f"  \\addplot[blue,thick] table[x=t,y=kv] {{tikz/ltcmlp_{a.case}_ltc.dat}}; \\addlegendentry{{LTC}}\n"
        f"  \\addplot[orange,thick] table[x=t,y=kv] {{tikz/ltcmlp_{a.case}_mlp.dat}}; \\addlegendentry{{MLP}}\n"
        "\\end{axis}\n\\end{tikzpicture}\n")
    print(f"wrote {TZ}/fig_ltc_vs_mlp_{a.case}_{a.seed}.tex")


if __name__ == "__main__":
    main()
