"""Hand-written pgfplots/TikZ versions of the lab_test online-learning figures (deploy qualifier).

Emits standalone-compilable .tex (documentclass=standalone + pgfplots) into
results/deploy_labtest/tikz/, with dense series written as separate .dat tables. Pure vector
pgfplots -- drop straight into an IEEE paper (lift the tikzpicture, or \\input the file).
Reuses the SAME committed data as the matplotlib figures:
  results/deploy_labtest/online_learn.npz   (the live learning drive; has reward/off/ret)
  results/deploy_labtest/qual_labtest.json  (the episodic keep-best ratchet)

    PYTHONPATH=...:. python3 tools/paper_online_tikz.py
"""
import sys, json
from pathlib import Path
import numpy as np
ROOT = Path("/home/poxx/github/mpcc-online-tuning"); sys.path.insert(0, str(ROOT))
OUT = ROOT / "results/deploy_labtest"
TZ = OUT / "tikz"; TZ.mkdir(parents=True, exist_ok=True)
DT = 0.05
FROZEN_FAST = 20.2

# palette (matches the matplotlib figures)
COLORS = {"kv": (33, 150, 243), "qc": (255, 152, 0), "ql": (76, 175, 80), "ra": (244, 67, 54),
          "banked": (46, 125, 50), "reverted": (211, 47, 47), "inc": (46, 125, 50),
          "ret": (25, 118, 210), "off": (211, 47, 47), "frozen": (0, 0, 0)}
WLAB = {"kv": r"$k_v$", "qc": r"$q_c$", "ql": r"$q_\ell$", "ra": r"$r_a$"}


def colordefs():
    return "\n".join(rf"\definecolor{{c{k}}}{{RGB}}{{{r},{g},{b}}}" for k, (r, g, b) in COLORS.items())


HEADER = r"""% Auto-generated by tools/paper_online_tikz.py -- lift the tikzpicture into your IEEE paper,
% or compile directly (pdflatex/lualatex). Needs pgfplots >= 1.16. Dense series read .dat tables
% that live next to this file.
\documentclass[tikz,border=2pt]{standalone}
\usepackage{pgfplots}
\pgfplotsset{compat=1.18}
\usepgfplotslibrary{groupplots}
%%COLORS%%
\begin{document}
"""
FOOTER = "\n\\end{document}\n"


def write(name, body):
    (TZ / f"{name}.tex").write_text(HEADER.replace("%%COLORS%%", colordefs()) + body + FOOTER)
    print(f"  wrote tikz/{name}.tex")


def coords(xs, ys):
    return " ".join(f"({x:.4g},{y:.4g})" for x, y in zip(xs, ys))


# ===================================================================== load the live drive
d = np.load(OUT / "online_learn.npz", allow_pickle=True)
th = d["th_hist"]; vh = d["vh"]; wn = [str(w) for w in d["weight_names"]]
lt = np.asarray(d["lap_times"], float); lb = [str(b) for b in d["lap_banked"]]
let = np.asarray(d["lap_end_tick"], int)
reward = np.asarray(d["reward"], float); off = np.asarray(d["off"], bool); ret = np.asarray(d["ret"], float)
N = len(th); tmin = np.arange(N) * DT / 60.0

# ---------------------------------------------------------- 1) keep-best lap-time curve (panel A)
real = [(float(lt[i]), lb[i]) for i in range(len(lt)) if float(lt[i]) > 3.0]
rt = [t for t, _ in real]; rb = [b for _, b in real]
xs = list(range(1, len(rt) + 1))
bx = [x for x, b in zip(xs, rb) if b == "banked"]; by = [t for t, b in zip(rt, rb) if b == "banked"]
rx = [x for x, b in zip(xs, rb) if b == "reverted"]; ry = [t for t, b in zip(rt, rb) if b == "reverted"]
ox = [x for x, b in zip(xs, rb) if b not in ("banked", "reverted")]
oy = [t for t, b in zip(rt, rb) if b not in ("banked", "reverted")]
inc = []; cur = np.inf
for t, b in zip(rt, rb):
    cur = min(cur, t) if b == "banked" else cur
    inc.append(cur if np.isfinite(cur) else None)
istep = [(x, v) for x, v in zip(xs, inc) if v is not None]
body = rf"""\begin{{tikzpicture}}
\begin{{axis}}[width=8.4cm,height=5.6cm,xlabel={{completed lap \#}},ylabel={{lap time [s]}},
  title={{Keep-best on lab\_test: one lucky bank, revert the rest}},
  grid=both,grid style={{gray!18}},legend pos=south east,legend style={{font=\scriptsize,fill opacity=0.85}},
  ymin=4,ymax={max(rt)+1.5:.3g},xmin=0.5,xmax={len(rt)+0.5}]
\addplot[const plot,ccinc,ultra thick,forget plot] coordinates {{{coords([x for x,_ in istep],[v for _,v in istep])}}};
\addlegendimage{{ccinc,ultra thick}}\addlegendentry{{keep-best net in place}}
\addplot[only marks,mark=*,creverted,mark size=2.2pt] coordinates {{{coords(rx,ry)}}}; \addlegendentry{{reverted}}
\addplot[only marks,mark=*,mark size=2.2pt,gray] coordinates {{{coords(ox,oy)}}}; \addlegendentry{{partial/off lap}}
\addplot[only marks,mark=star,cbanked,mark size=4pt] coordinates {{{coords(bx,by)}}}; \addlegendentry{{banked (13.8\,s)}}
\addplot[dashed,cfrozen,thick] coordinates {{(0.5,{FROZEN_FAST})({len(rt)+0.5},{FROZEN_FAST})}}; \addlegendentry{{frozen pace {FROZEN_FAST}\,s}}
\end{{axis}}
\end{{tikzpicture}}"""
write("online_keepbest_laptime", body)

# ---------------------------------------------------------- 2) weights adapting (panel D) -> .dat
W = 600
roll = lambda a: np.convolve(a, np.ones(W) / W, mode="valid")
tw = {k: th[:, wn.index(name)] for k, name in (("kv", "k_v"), ("qc", "q_c"), ("ql", "q_l"), ("ra", "r_a"))}
twr = {k: roll(v) / (abs(v[0]) + 1e-9) for k, v in tw.items()}
tt = tmin[W - 1:]
step = max(1, len(tt) // 350)                               # downsample for a clean vector file
idx = np.arange(0, len(tt), step)
with open(TZ / "online_weights.dat", "w") as f:
    f.write("t kv qc ql ra\n")
    for i in idx:
        f.write(f"{tt[i]:.4f} {twr['kv'][i]:.5f} {twr['qc'][i]:.5f} {twr['ql'][i]:.5f} {twr['ra'][i]:.5f}\n")
body = r"""\begin{tikzpicture}
\begin{axis}[width=8.4cm,height=5.6cm,xlabel={time [min]},ylabel={weight / initial},
  title={Online-tuned weights adapting (30\,s rolling mean)},
  grid=both,grid style={gray!18},legend pos=north east,legend style={font=\scriptsize,fill opacity=0.85}]
""" + "\n".join(
    rf"\addplot[c{k},thick] table[x=t,y={k}] {{online_weights.dat}}; \addlegendentry{{{WLAB[k]}}}"
    for k in ("kv", "qc", "ql", "ra")) + r"""
\end{axis}
\end{tikzpicture}"""
write("online_weights", body)

# ---------------------------------------------------------- 3) online reward / return (panels B,C) -> .dat
step2 = max(1, N // 500); ridx = np.arange(0, N, step2)
with open(TZ / "online_return.dat", "w") as f:
    f.write("t ret\n")
    for i in ridx:
        f.write(f"{tmin[i]:.4f} {ret[i]:.4f}\n")
ot = np.where(off)[0]
offc = coords(tmin[ot], ret[ot])
body = rf"""\begin{{tikzpicture}}
\begin{{axis}}[width=8.4cm,height=5.6cm,xlabel={{time [min]}},ylabel={{return $\sum r$}},
  title={{Online reward: return (down-steps = off-track $-5$)}},
  grid=both,grid style={{gray!18}},legend pos=north west,legend style={{font=\scriptsize,fill opacity=0.85}}]
\addplot[cret,thick] table[x=t,y=ret] {{online_return.dat}}; \addlegendentry{{cumulative return}}
\addplot[only marks,mark=*,coff,mark size=1.1pt] coordinates {{{offc}}}; \addlegendentry{{off-track tick ($-5$), {len(ot)} total}}
\end{{axis}}
\end{{tikzpicture}}"""
write("online_reward", body)

# ---------------------------------------------------------- 4) episodic keep-best ratchet (qual_labtest.json)
j = json.load(open(OUT / "qual_labtest.json"))
seeds = [0, 1, 2]; SC = {0: "ql", 1: "ra", 2: "ret"}       # reuse defined colors: green, red, blue
lines = []
for s in seeds:
    ep = j["episodes"][f"icra_t2_smooth|{s}|tuner"]
    n = [e["ep"] for e in ep]; best = [e["best"] if e["best"] is not None else 0 for e in ep]
    lines.append(rf"\addplot[const plot,c{SC[s]},thick] coordinates {{{coords(n,best)}}}; \addlegendentry{{seed {s}}}")
    acts = [e["action"] for e in ep]; offs = [e["off"] for e in ep]; laps = [e["laps"] for e in ep]
    bx2 = [x for x, a, o in zip(n, acts, offs) if a == "banked" and not o]
    by2 = [l for l, a, o in zip(laps, acts, offs) if a == "banked" and not o]
    lines.append(rf"\addplot[only marks,mark=*,c{SC[s]},mark size=1.6pt,forget plot] coordinates {{{coords(bx2,by2)}}};")
body = r"""\begin{tikzpicture}
\begin{axis}[width=8.4cm,height=5.6cm,xlabel={online-learning episode},ylabel={keep-best laps (incumbent)},
  title={Episodic keep-best ratchet (frozen-validated) -- produces seed 2},
  grid=both,grid style={gray!18},legend pos=south east,legend style={font=\scriptsize,fill opacity=0.85}]
""" + "\n".join(lines) + r"""
\end{axis}
\end{tikzpicture}"""
write("online_episodic_ratchet", body)

print(f"done -> {TZ}")
