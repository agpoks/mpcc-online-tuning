#!/usr/bin/env python3
"""RQ2 memory figure (honest): recurrent (LTC) vs memoryless (MLP) on the EQUAL-pace occluded
opponent, in TWO regimes side by side so the reader sees which part of the advantage is a learning
transient and which part survives on the shipped policy:
  - ONLINE-LEARNING aggregate  (results/race_phase2/race_phase2_fov_s123.json, equal rows, n=11/arm):
    the car is still adapting; MLP's low clean-rate is mostly CONTACT during early exploration.
  - DEPLOYED FROZEN             (results/race_phase2/equal_frozen_sweep.npz, n=9 matched starts):
    both nets replayed with learning OFF on matched s0/v0/opponent under the 270-deg occluding sensor.
The honest reading: the big clean-rate gap (0.91 vs 0.36) collapses when frozen (1.00 vs 0.89) -- it was
largely the adaptation transient -- but the PASS-COMPLETION gap (~0.2) is stable across both regimes:
LTC finishes occluded passes the memoryless net abandons. Emits pgfplots TikZ (for the paper) + a PNG
preview. DATA-ONLY (no acados). Reproduce:  python3 tools/paper_memory_bars.py
"""
import sys, json
from pathlib import Path
from collections import defaultdict
import numpy as np

ROOT = Path("/home/poxx/github/mpcc-online-tuning")
FOV = ROOT / "results/race_phase2/race_phase2_fov_s123.json"
SWEEP = ROOT / "results/race_phase2/equal_frozen_sweep.npz"
TEX = Path("/home/poxx/github/R-AL-MPCC_online_learning/figures/memory_bars.tex")
PNG = ROOT / "results/race_phase2/memory_bars.png"
LTC_C, MLP_C = "#1f77b4", "#ff7f0e"   # tab10 blue / orange (house style)


def online_equal():
    d = json.load(open(FOV)); cl = defaultdict(list); ps = defaultdict(list); n = defaultdict(int)
    for r in d["runs"]:
        for row in r["rows"]:
            if row.get("kind") != "equal":
                continue
            cl[r["arm"]].append(1.0 if row.get("clean") else 0.0)
            ps[r["arm"]].append(1.0 if (row.get("passes") or 0) > 0 else 0.0)
            n[r["arm"]] += 1
    return {a: dict(clean=float(np.mean(cl[a])), passr=float(np.mean(ps[a])), n=n[a]) for a in ("ltc", "mlp")}


def deployed_equal():
    rows = np.load(SWEEP, allow_pickle=True)["rows"].tolist()
    out = {}
    for a in ("ltc", "mlp"):
        r = [x for x in rows if x["arm"] == a]
        out[a] = dict(clean=float(np.mean([x["clean"] for x in r])),
                      passr=float(np.mean([x["passed"] for x in r])), n=len(r))
    return out


def emit_tex(on, dp):
    # four x groups: clean(online), clean(deployed), pass(online), pass(deployed).
    # Two-line labels via align=center + \\ (no comma in the label -> no tick-list parsing ambiguity).
    cats = ["clean\\\\(learning)", "clean\\\\(deployed)", "pass\\\\(learning)", "pass\\\\(deployed)"]
    ltc = [on["ltc"]["clean"], dp["ltc"]["clean"], on["ltc"]["passr"], dp["ltc"]["passr"]]
    mlp = [on["mlp"]["clean"], dp["mlp"]["clean"], on["mlp"]["passr"], dp["mlp"]["passr"]]
    coords = lambda v: " ".join(f"({i},{x:.3f})" for i, x in enumerate(v))
    tex = rf"""% RQ2 memory advantage, equal-pace occluded opponent. Auto-generated by
% tools/paper_memory_bars.py from race_phase2_fov_s123.json + equal_frozen_sweep.npz. Do not hand-edit.
% online-learning n={on['ltc']['n']}/arm (equal episodes); deployed frozen n={dp['ltc']['n']}/arm (matched starts).
\begin{{tikzpicture}}
\begin{{axis}}[
  width=\linewidth, height=3.6cm,
  ybar=1.2pt, bar width=7pt,
  ymin=0, ymax=1.18, ytick={{0,0.25,0.5,0.75,1.0}},
  ylabel={{rate}}, ylabel near ticks,
  xtick={{0,1,2,3}},
  xticklabels={{{', '.join('{'+c+'}' for c in cats)}}},
  xticklabel style={{align=center, font=\scriptsize}},
  x tick label as interval=false,
  enlarge x limits=0.14,
  tick align=outside, tickpos=left,
  axis lines*=left,
  legend style={{at={{(0.5,1.02)}}, anchor=south, legend columns=2, font=\footnotesize, draw=none}},
  nodes near coords, nodes near coords style={{font=\tiny, /pgf/number format/fixed, /pgf/number format/precision=2}},
  every node near coord/.append style={{yshift=-1pt}},
]
\addplot[fill={{rgb,255:red,31;green,119;blue,180}}, draw=black!40] coordinates {{{coords(ltc)}}};
\addplot[fill={{rgb,255:red,255;green,127;blue,14}}, draw=black!40] coordinates {{{coords(mlp)}}};
\legend{{LTC (recurrent), MLP (memoryless)}}
% divider between the two regimes within each metric is implicit in the xtick labels.
\end{{axis}}
\end{{tikzpicture}}
"""
    TEX.parent.mkdir(parents=True, exist_ok=True)
    TEX.write_text(tex)
    print("wrote", TEX)


def emit_png(on, dp):
    import matplotlib; matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.family": "serif", "font.size": 9})
    cats = ["clean\n(learning)", "clean\n(deployed)", "pass\n(learning)", "pass\n(deployed)"]
    ltc = [on["ltc"]["clean"], dp["ltc"]["clean"], on["ltc"]["passr"], dp["ltc"]["passr"]]
    mlp = [on["mlp"]["clean"], dp["mlp"]["clean"], on["mlp"]["passr"], dp["mlp"]["passr"]]
    x = np.arange(4); w = 0.38
    fig, ax = plt.subplots(figsize=(6.4, 3.2), constrained_layout=True)
    b1 = ax.bar(x - w / 2, ltc, w, color=LTC_C, label="LTC (recurrent)", edgecolor="k", lw=0.4)
    b2 = ax.bar(x + w / 2, mlp, w, color=MLP_C, label="MLP (memoryless)", edgecolor="k", lw=0.4)
    for bb in (b1, b2):
        ax.bar_label(bb, fmt="%.2f", fontsize=7, padding=1)
    ax.axvline(1.5, color="0.7", lw=0.8, ls=":")  # clean | pass divider
    ax.set_xticks(x); ax.set_xticklabels(cats, fontsize=8)
    ax.set_ylim(0, 1.1); ax.set_yticks([0, .25, .5, .75, 1.0]); ax.set_ylabel("rate")
    ax.legend(fontsize=8, loc="upper center", ncol=2, frameon=False, bbox_to_anchor=(0.5, 1.16))
    ax.spines[["top", "right"]].set_visible(False); ax.grid(axis="y", alpha=0.25)
    PNG.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(PNG, dpi=200, bbox_inches="tight")
    print("wrote", PNG)


def main():
    on, dp = online_equal(), deployed_equal()
    print(f"online  equal: LTC clean {on['ltc']['clean']:.2f} pass {on['ltc']['passr']:.2f} (n={on['ltc']['n']}) | "
          f"MLP clean {on['mlp']['clean']:.2f} pass {on['mlp']['passr']:.2f} (n={on['mlp']['n']})")
    print(f"deployed equal: LTC clean {dp['ltc']['clean']:.2f} pass {dp['ltc']['passr']:.2f} (n={dp['ltc']['n']}) | "
          f"MLP clean {dp['mlp']['clean']:.2f} pass {dp['mlp']['passr']:.2f} (n={dp['mlp']['n']})")
    emit_tex(on, dp); emit_png(on, dp)


if __name__ == "__main__":
    main()
